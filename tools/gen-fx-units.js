//
// gen-fx-units.js — bakes the server-side unit tables the FX bench needs into
// one client-readable file: client/data/fx-units.json.
//
// client/dev/test-fx.html runs the REAL ProjectileModel against synthetic units, and
// ProjectileModel.specFor() reads `unit.meta.combat` — which normally arrives on
// each unit inside a parsed .wc3v. The bench has no replay, so it has to build
// meta itself, and helpers/ is not served to the browser.
//
// Regenerate whenever helpers/unitCombat.json or helpers/unitMovement.json
// changes:  node tools/gen-fx-units.js
//
// This is a COPY of authoritative data, so it must never be hand-edited and must
// never be read by anything other than the bench. The viewer keeps getting its
// combat block from the parser, exactly as before.
//
const fs = require('fs');
const path = require('path');

const combat = require('../helpers/unitCombat.json').units;
const movement = require('../helpers/unitMovement.json').units;
const mappings = require('../helpers/mappings.js');
const UP = require('../client/js/UnitProjectiles.js');

const OUT = path.join(__dirname, '..', 'client', 'data', 'fx-units.json');

function displayNameFor (itemId) {
  try {
    const info = mappings.getUnitInfo(itemId);
    if (info && info.displayName) return info.displayName;
  } catch (e) { /* unknown id — fall through to the raw id */ }
  return itemId;
}

const units = {};
let withProjectile = 0;

// Every unit that can attack at all. Melee units are deliberately INCLUDED:
// "a melee unit draws no projectile" is a property the bench has to be able to
// check, and it can't check what it can't select.
for (const itemId of Object.keys(combat)) {
  const mv = movement[itemId] || {};
  const meta = { combat: combat[itemId] };
  if (mv.moveType) meta.moveType = mv.moveType;
  if (mv.moveHeight != null) meta.moveHeight = mv.moveHeight;
  if (mv.moveSpeed) meta.movespeed = mv.moveSpeed;
  if (mv.turnRate != null) meta.turnRate = mv.turnRate;

  const hasProjectile = !!(UP.units && UP.units[itemId]);
  if (hasProjectile) withProjectile++;

  units[itemId] = {
    displayName: displayNameFor(itemId),
    hasProjectile,
    weaponType: combat[itemId].weaponType || 'normal',
    attackType: combat[itemId].attackType || 'normal',
    meta
  };
}

const out = {
  version: 1,
  generated: new Date().toISOString().slice(0, 10),
  source: 'helpers/unitCombat.json + helpers/unitMovement.json',
  note: 'Generated by tools/gen-fx-units.js for client/dev/test-fx.html. Do not hand-edit.',
  units
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(out, null, 1));

const ids = Object.keys(units);
const ranged = ids.filter(id => units[id].weaponType !== 'normal');
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
console.log(`  ${ids.length} units with combat data`);
console.log(`  ${ranged.length} non-melee, ${withProjectile} with a UnitProjectiles entry`);
console.log(`  ${(fs.statSync(OUT).size / 1024).toFixed(0)} KB`);
