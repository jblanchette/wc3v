/**
 * gen-item-names.js — freeze the itemId → display-name lookup that the build
 * pages need into a small committed file.
 *
 * WHY THIS EXISTS, and why gen-seo does not just require helpers/mappings.js:
 *
 * mappings.js requires ./UnitBalance.json, which is SLK-derived Blizzard game
 * data and is gitignored (`helpers/UnitBalance*` in .gitignore, alongside
 * slk/UnitBalance*). It is the only untracked dependency mappings.js has. So on
 * Render — which builds from a clean clone — requiring mappings.js throws
 * MODULE_NOT_FOUND and the whole build fails. It did, on 2026-08-11.
 *
 * The build pages only need names for the closed set of itemIds that appear in
 * builds-manifest.json, about a hundred of them. So resolve them here, on a dev
 * machine where UnitBalance.json exists, and commit the result. The Render build
 * then reads a plain JSON file and needs no game data at all.
 *
 * Run this after changing builds-manifest.json or the mappings tables:
 *   npm run gen-item-names
 *
 * `node tools/gen-seo.js` fails if the manifest references an id this file does
 * not cover, so a forgotten run is caught at build time rather than shipping a
 * raw four-letter id onto a published page.
 *
 * Usage:
 *   node tools/gen-item-names.js
 *   node tools/gen-item-names.js --check    exit 1 if the committed file is stale
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const MANIFEST = path.join(ROOT, 'client', 'data', 'builds-manifest.json');
const OUT = path.join(__dirname, 'seo', 'item-names.json');

const check = process.argv.includes('--check');

/** Every itemId the build pages render a name for. Mirrors seo/build-page.js. */
function collectIds (manifest) {
  const ids = new Set();
  const add = (v) => { if (typeof v === 'string' && v) ids.add(v); };

  for (const b of manifest.builds) {
    (b.keyUnits || []).forEach(add);
    (b.coreUpgrades || []).forEach(add);
    add(b.heroItemId);
    (b.heroItemIds || []).forEach(add);

    const tp = b.tierProgression || {};
    for (const k of ['t1', 't2', 't3']) {
      const t = tp[k];
      if (!t) continue;
      (t.buildings || []).forEach(add);
      (t.units || []).forEach(add);
    }

    for (const [heroId, skills] of Object.entries(b.heroSkills || {})) {
      add(heroId);
      Object.keys(skills || {}).forEach(add);
    }
  }
  return [...ids].sort();
}

function main () {
  if (!fs.existsSync(MANIFEST)) {
    console.error('gen-item-names: missing ' + path.relative(ROOT, MANIFEST));
    process.exit(1);
  }

  let mappings;
  try {
    mappings = require('../helpers/mappings');
  } catch (e) {
    console.error('gen-item-names: could not load helpers/mappings.js — ' + e.message);
    console.error('  This tool only runs on a dev machine. helpers/UnitBalance.json is');
    console.error('  gitignored, so mappings.js cannot load from a clean clone.');
    process.exit(1);
  }
  const { getUnitInfo, researchMeta } = mappings;

  const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
  const ids = collectIds(manifest);

  const names = {};
  const unresolved = [];

  for (const id of ids) {
    const r = researchMeta && researchMeta[id];
    if (r && r.name) { names[id] = r.name; continue; }

    const direct = getUnitInfo(id);
    if (direct && direct.isKnownId && direct.displayName) { names[id] = direct.displayName; continue; }

    // Hero ids are capitalised in mappings ('Udea') and lowercased in the
    // manifest's heroSkills keys ('udea').
    const cased = id[0].toUpperCase() + id.slice(1).toLowerCase();
    const alt = cased !== id ? getUnitInfo(cased) : null;
    if (alt && alt.isKnownId && alt.displayName) { names[id] = alt.displayName; continue; }

    unresolved.push(id);
  }

  const out = {
    note: 'GENERATED by tools/gen-item-names.js. Do not hand-edit. Frozen here ' +
          'because helpers/mappings.js depends on gitignored SLK data and cannot ' +
          'be required in the Render build.',
    generatedFrom: 'client/data/builds-manifest.json',
    count: Object.keys(names).length,
    names
  };
  const json = JSON.stringify(out, null, 2) + '\n';

  if (unresolved.length) {
    console.error('gen-item-names: ' + unresolved.length + ' unresolved itemId(s): ' + unresolved.join(', '));
    console.error('  Add them to allItemIds in helpers/mappings.js, or fix the manifest.');
    process.exit(1);
  }

  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  const changed = prev !== json;

  if (check) {
    console.log('item-names: ' + Object.keys(names).length + ' id(s), ' +
      (changed ? 'STALE' : 'up to date'));
    if (changed) {
      console.error('gen-item-names --check: tools/seo/item-names.json is stale. Run `npm run gen-item-names`.');
      process.exit(1);
    }
    return;
  }

  if (changed) fs.writeFileSync(OUT, json);
  console.log('item-names: ' + Object.keys(names).length + ' id(s) → ' +
    path.relative(ROOT, OUT) + (changed ? '' : ' (unchanged)'));
}

main();
