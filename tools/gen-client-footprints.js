/**
 * Generate client/js/BuildingFootprints.js — a browser-loadable lookup of
 * real building footprints for the Building Placement viewer.
 *
 * Source of truth: helpers/buildingPathing.json (parsed from WC3 PathTextures
 * TGAs by tools/parse-building-pathing.js). We emit the SOLID footprint
 * (walkBbox — the walk-blocked core that matches the building model), in
 * 32-unit build cells, plus the full pathing-texture dims for reference.
 *
 * The client can't require() server JSON, so this bakes a compact window
 * global. Re-run after regenerating buildingPathing.json:
 *   node tools/gen-client-footprints.js
 */

const fs = require('fs');
const path = require('path');

const manifest = require('../helpers/buildingPathing.json');
const OUT = path.join(__dirname, '..', 'client', 'js', 'BuildingFootprints.js');

const out = {};
for (const [itemId, b] of Object.entries(manifest.buildings)) {
  const wb = b.walkBbox;
  // Prefer the solid walk-blocked footprint; fall back to the full texture
  // (SimpleSolid textures have no margin, so the two coincide there).
  const w = wb ? wb.widthCells : b.widthCells;
  const h = wb ? wb.heightCells : b.heightCells;
  const ox = wb ? (wb.offsetX || 0) : 0;
  const oy = wb ? (wb.offsetY || 0) : 0;
  // [solidW, solidH] cells, [offX, offY] world units, [fullW, fullH] cells.
  out[itemId] = [w, h, ox, oy, b.widthCells, b.heightCells];
}

const banner = '// GENERATED by tools/gen-client-footprints.js from ' +
  'helpers/buildingPathing.json — do not edit by hand.\n' +
  '// Format: itemId -> [solidWcells, solidHcells, offX, offY, fullWcells, fullHcells]\n';

const body = 'window.WC3V_BUILDING_FOOTPRINTS = ' + JSON.stringify(out) + ';\n';

fs.writeFileSync(OUT, banner + body);
console.log('Wrote ' + OUT + ' (' + Object.keys(out).length + ' buildings)');
