/**
 * Build the desktop app's item classification lookup:
 *   helpers/mappings.js + helpers/dropTables.json
 *     → desktop/src-frontend/js/item-classes.js
 *
 * WHY THIS EXISTS
 *
 * The desktop build card wants to split a player's shop purchases into what
 * they KEPT (claws, orbs, boots — build decisions) and what they SPENT
 * (potions, scrolls, tomes — volume), so that a game with fourteen healing
 * potions does not render fourteen icons.
 *
 * The stored summary cannot answer that. `SummaryExtract.extractItemPurchases`
 * emits `{ itemId, name, gameTimeMs, goldCost, ... }` with no category, and
 * adding one is a schema bump plus a re-parse of the whole corpus — the wrong
 * trade for something only the renderer needs. The parser bundle carries
 * `itemAbilityData` internally but `client/js/parser/parserEntry.js` exports
 * only parse/peekPlayers/parseToWc3v, so the UI cannot reach it at runtime.
 *
 * So: precompute the one bit the card needs, ship it as a plain script, and it
 * works on every summary already on disk.
 *
 * CLASSIFICATION, in precedence order
 *
 *   1. helpers/mappings.js `itemAbilityData[id].category` — the hand-curated
 *      melee table, and the one that is actually right about orbs.
 *        'consumable' | 'tome'      → CONSUMED
 *        'permanent'  | 'active'    → KEPT
 *   2. helpers/dropTables.json `items[id].class` — the CASC dump, used only for
 *      ids the table above does not cover (creep-drop artifacts, campaign).
 *        'PowerUp'                  → CONSUMED
 *        everything else            → KEPT
 *   3. Unknown id                   → KEPT (the renderer's default)
 *
 * The two sources disagree on purpose-built cases — `ofir` (Orb of Fire) is
 * 'permanent' in itemAbilityData and class 'Miscellaneous' in dropTables;
 * `phea` (potion) and `stwp` (town portal) are both class 'Purchasable', which
 * says nothing about permanence. itemAbilityData wins wherever it has an
 * opinion, which is what the precedence above encodes.
 *
 * KNOWN IMPRECISION, recorded rather than fixed: charged 'active' items — wands,
 * Necklace of Spiritual Wisdom, Staff of Teleportation — are spent in play but
 * classed KEPT here. They hold a bag slot for most of the game and read as
 * equipment on a build card, which is the question this table answers.
 *
 * Only the CONSUMED set is emitted. It is the smaller half, and "not in the set"
 * is exactly the KEPT default the renderer wants for unknown ids.
 *
 * Re-run after any change to itemAbilityData or dropTables.json, and commit the
 * output — desktop/src-frontend is the source tree, desktop/dist is generated
 * from it by tools/build-desktop-client.js.
 */

const fs = require('fs');
const path = require('path');
const { itemAbilityData } = require('../helpers/mappings');
const dropTables = require('../helpers/dropTables.json');

const OUTPUT_PATH = path.join(
  __dirname, '..', 'desktop', 'src-frontend', 'js', 'item-classes.js'
);

// itemAbilityData is keyed by BOTH item ids and hero/item ability ids (`AHwe`
// is Water Elemental, an ability, not something a shop sells). Ability ids are
// harmless here — a purchase record never carries one — so they are left in
// rather than filtered on a guess about the id space.
const CONSUMED_CATEGORIES = new Set(['consumable', 'tome']);
const CONSUMED_CLASSES = new Set(['PowerUp']);

const consumed = new Set();
const counts = { category: 0, class: 0 };

for (const [itemId, data] of Object.entries(itemAbilityData)) {
  if (data && CONSUMED_CATEGORIES.has(data.category)) {
    consumed.add(itemId);
    counts.category++;
  }
}

for (const [itemId, data] of Object.entries(dropTables.items || {})) {
  // itemAbilityData has already spoken about this id, either way.
  if (itemAbilityData[itemId]) continue;
  if (data && CONSUMED_CLASSES.has(data.class)) {
    consumed.add(itemId);
    counts.class++;
  }
}

const ids = Array.from(consumed).sort();

// Wrapped at a readable width rather than one id per line: 60-odd short keys
// down a column is a file nobody scans.
const INDENT = ' '.repeat(6);
const lines = [];
let current = '';
ids.forEach((id, i) => {
  const entry = `${JSON.stringify(id)}: 1${i === ids.length - 1 ? '' : ','}`;
  const next = current ? `${current} ${entry}` : `${INDENT}${entry}`;
  if (next.length > 76 && current) {
    lines.push(current);
    current = `${INDENT}${entry}`;
  } else {
    current = next;
  }
});
if (current) lines.push(current);

const out = `// GENERATED by tools/build-item-classes.js — do not edit by hand.
//
// Which shop items are SPENT rather than KEPT, for the build card's Bought row.
// Derived from helpers/mappings.js (itemAbilityData.category) with
// helpers/dropTables.json (items[].class) as the fallback; see the generator
// for the precedence rules and the one known imprecision (charged 'active'
// items are classed kept).
//
// Only the consumed set is listed. Anything absent — including an id this
// build has never seen — is kept, which is the safe default: an unclassified
// artifact belongs beside the permanents.
//
// ${ids.length} ids: ${counts.category} from itemAbilityData, ${counts.class} from dropTables.

(function () {
  'use strict';

  window.ItemClasses = {
    consumed: {
${lines.join('\n')}
    },

    isConsumed (itemId) {
      return !!(itemId && this.consumed[itemId]);
    }
  };
})();
`;

fs.writeFileSync(OUTPUT_PATH, out);

console.log(`item-classes.js: ${ids.length} consumed ids ` +
  `(${counts.category} itemAbilityData, ${counts.class} dropTables)`);
console.log(`  → ${path.relative(path.join(__dirname, '..'), OUTPUT_PATH)}`);
